// Interaction QA: opens a detail, the flat breakdown and the box. node scripts/interact.mjs <outDir> [w] [h]
import puppeteer from "puppeteer-core";
const [out, w = "1440", h = "900"] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", args: ["--use-angle=d3d11", "--enable-webgl", "--ignore-gpu-blocklist"] });
const page = await browser.newPage();
const mobile = +w < 700;
await page.setViewport({ width: +w, height: +h, isMobile: mobile, hasTouch: mobile });
page.on("pageerror", (e) => console.log("pageerror", e.message));
page.on("console", (m) => m.type() === "error" && !m.text().includes("unmount") && console.log("console", m.text().slice(0, 160)));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const go = async (id, off = 0) => { await page.evaluate((id, off) => { const el = document.getElementById(id); window.scrollTo(0, el.getBoundingClientRect().top + scrollY + off); }, id, off); await wait(2600); };
await page.goto("http://localhost:3300/", { waitUntil: "networkidle2", timeout: 120000 });
await wait(1500);
await go("chapter-postcard", 200);
await page.evaluate(() => [...document.querySelectorAll("button")].find((b) => b.textContent.includes("The Mumbai Local"))?.click());
await wait(1400);
await page.screenshot({ path: `${out}/i-${w}-detail.png` });
await page.keyboard.press("Escape");
await wait(800);
await go("chapter-type", 200);
await page.evaluate(() => [...document.querySelectorAll("button")].find((b) => b.textContent.includes("Flat graphic breakdown"))?.click());
await wait(1600);
await page.screenshot({ path: `${out}/i-${w}-flat.png` });
await go("packaging", 450);
await page.evaluate(() => [...document.querySelectorAll("button")].find((b) => b.textContent.includes("Open the box"))?.click());
await wait(4500);
await page.screenshot({ path: `${out}/i-${w}-boxopen.png` });
await page.goto("http://localhost:3300/case-study", { waitUntil: "networkidle2" });
await wait(1500);
await page.screenshot({ path: `${out}/i-${w}-case.png` });
await browser.close();
